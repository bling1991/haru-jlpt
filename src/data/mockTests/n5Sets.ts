// Clean up kanjis in N5_VREAD_POOL[i][0] so vocab note displays only the bracketed word
const CLEAN_N5_VREAD_POOL = N5_VREAD_POOL.map((row) => {
  const match = row[0].match(/【([^】]+)】/);
  return [
    match ? match[1] : row[0],
    row[1],
    row[2],
    row[3],
    row[4],
    row[5],
    row[6],
  ] as typeof row;
});

const cache = new Map<number, QuizQuestion[]>();

export function getN5MockTest(testNumber: number): QuizQuestion[] {
  const cached = cache.get(testNumber);
  if (cached) return cached;

  const idx = Math.max(0, Math.min(8, testNumber - 2));
  const spec: SingleMockTestSpec = {
    testNumber,
    vRead: CLEAN_N5_VREAD_POOL.slice(idx * 7, idx * 7 + 7),
    vOrtho: N5_VORTHO_POOL.slice(idx * 5, idx * 5 + 5),
    vCtx: N5_VCTX_POOL.slice(idx * 7, idx * 7 + 7),
    vSyn: N5_VSYN_POOL.slice(idx * 4, idx * 4 + 4),
    vUse: N5_VUSE_POOL.slice(idx * 2, idx * 2 + 2),
    gSent: N5_GSENT_POOL.slice(idx * 10, idx * 10 + 10),
    gStar: N5_GSTAR_POOL.slice(idx * 4, idx * 4 + 4),
    gText: [N5_GTEXT_POOL[idx]],
    reading: N5_READING_BY_TEST[idx],
    listening: N5_LISTENING_BY_TEST[idx],
  };

  const compiled = compileMockTestSpec(JlptLevel.N5, spec, N5_VCTX_POOL);
  cache.set(testNumber, compiled);
  return compiled;
}
