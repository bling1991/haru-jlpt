const rShort = (
  passage: string,
  prompt: string,
  correct: string,
  wrongs: [string, string, string],
  reading: string,
  ko: string,
  exp: string
): ReadingPassageBlock => ({
  code: 'R_SHORT',
  passage,
  questions: [[prompt, correct, wrongs, reading, ko, exp]],
});

const rMid = (
  passage: string,
  q1: [string, string, [string, string, string], string, string, string],
  q2: [string, string, [string, string, string], string, string, string]
): ReadingPassageBlock => ({
  code: 'R_MID',
  passage,
  questions: [q1, q2],
});

