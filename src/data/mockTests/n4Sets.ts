const cache = new Map<number, QuizQuestion[]>();

export function getN4MockTest(testNumber: number): QuizQuestion[] {
  const cached = cache.get(testNumber);
  if (cached) return cached;

  const idx = Math.max(0, Math.min(8, testNumber - 2));
  const spec: SingleMockTestSpec = {
    testNumber,
    vRead: N4_VREAD_POOL.slice(idx * 8, idx * 8 + 8),
    vOrtho: N4_VORTHO_POOL.slice(idx * 6, idx * 6 + 6),
    vCtx: N4_VCTX_POOL.slice(idx * 9, idx * 9 + 9),
    vSyn: N4_VSYN_POOL.slice(idx * 4, idx * 4 + 4),
    vUse: N4_VUSE_POOL.slice(idx * 3, idx * 3 + 3),
    gSent: N4_GSENT_POOL.slice(idx * 11, idx * 11 + 11),
    gStar: N4_GSTAR_POOL.slice(idx * 4, idx * 4 + 4),
    gText: [N4_GTEXT_POOL[idx]],
    reading: N4_READING_BY_TEST[idx],
    listening: N4_LISTENING_BY_TEST[idx],
  };

  const compiled = compileMockTestSpec(JlptLevel.N4, spec, N4_VCTX_POOL);
  cache.set(testNumber, compiled);
  return compiled;
}
