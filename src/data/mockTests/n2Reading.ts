const rShort = (
  passage: string,
  prompt: string,
  correct: string,
  wrongs: [string, string, string],
  reading: string,
  ko: string,
  exp: string
): ReadingPassageBlock => ({
  code: 'R_SHORT',
  passage,
  questions: [[prompt, correct, wrongs, reading, ko, exp]],
});

