const cache = new Map<number, QuizQuestion[]>();

export function getN5SupplementQuestions(testNumber: number): QuizQuestion[] {
  const cached = cache.get(testNumber);
  if (cached) return cached;

  const idx = Math.max(0, Math.min(9, testNumber - 1));
  const spec: LevelTestSupplementSpec = {
    vRead: VREAD_30.slice(idx * 3, idx * 3 + 3),
    vOrtho: VORTHO_30.slice(idx * 3, idx * 3 + 3),
    vCtx: VCTX_20.slice(idx * 2, idx * 2 + 2),
    gSent: GSENT_60.slice(idx * 6, idx * 6 + 6),
    gStar: [GSTAR_10[idx]],
    gText: [GTEXT_10[idx]],
  };

  const compiled = compileSupplementSpec(JlptLevel.N5, testNumber, spec);
  cache.set(testNumber, compiled);
  return compiled;
}
