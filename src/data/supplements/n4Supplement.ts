const cache = new Map<number, QuizQuestion[]>();

export function getN4SupplementQuestions(testNumber: number): QuizQuestion[] {
  const cached = cache.get(testNumber);
  if (cached) return cached;

  const idx = Math.max(0, Math.min(9, testNumber - 1));
  const spec: LevelTestSupplementSpec = {
    vRead: VREAD_20.slice(idx * 2, idx * 2 + 2),
    vOrtho: [VORTHO_10[idx]],
    vSyn: [VSYN_10[idx]],
    gSent: GSENT_40.slice(idx * 4, idx * 4 + 4),
    gStar: [GSTAR_10[idx]],
    gText: [GTEXT_10[idx]],
    listening: LISTENING_30.slice(idx * 3, idx * 3 + 3),
  };

  const compiled = compileSupplementSpec(JlptLevel.N4, testNumber, spec);
  cache.set(testNumber, compiled);
  return compiled;
}
