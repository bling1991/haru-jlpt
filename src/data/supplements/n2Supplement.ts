const cache = new Map<number, QuizQuestion[]>();

export function getN2SupplementQuestions(testNumber: number): QuizQuestion[] {
  const cached = cache.get(testNumber);
  if (cached) return cached;

  const idx = Math.max(0, Math.min(9, testNumber - 1));
  const spec: LevelTestSupplementSpec = {
    vRead: VREAD_20.slice(idx * 2, idx * 2 + 2),
    vOrtho: VORTHO_20.slice(idx * 2, idx * 2 + 2),
    vForm: VFORM_20.slice(idx * 2, idx * 2 + 2),
    vCtx: VCTX_20.slice(idx * 2, idx * 2 + 2),
    vSyn: [VSYN_10[idx]],
    vUse: [VUSE_10[idx]],
    gSent: GSENT_20.slice(idx * 2, idx * 2 + 2),
    reading: READING_10[idx],
  };

  const compiled = compileSupplementSpec(JlptLevel.N2, testNumber, spec);
  cache.set(testNumber, compiled);
  return compiled;
}
